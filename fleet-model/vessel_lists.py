"""Roster-derived lists for the Find box's vessel groups.

    python vessel_lists.py        data/roster.json -> functions/api/fleet/_roster_lists.js

The Pages Function behind /api/fleet/vessels sorts every hull the live logger
hears into groups (functions/api/fleet/_groups.js). Three of its inputs come
from the roster: the fleet itself, the hulls the roster rejected but whose
names match a landing's fleet list (`candidates`), and the fleet-list names
never matched on AIS (`unmatched_fleet_list`). This writes them as a small ES
module the Function can bundle. roster.py runs it after every rebuild, and
tests/fleetGroups.test.js fails if the module drifts from roster.json.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROSTER = os.path.join(HERE, "data", "roster.json")
OUT = os.path.join(HERE, "..", "functions", "api", "fleet", "_roster_lists.js")


def norm(s):
    """Same key as _groups.js normName(): letters and digits, upper case."""
    return re.sub(r"[^A-Z0-9]", "", str(s or "").upper())


def build(roster_path=ROSTER, out_path=OUT):
    with open(roster_path, encoding="utf-8") as f:
        r = json.load(f)
    fleet = {str(b["mmsi"]): b.get("name") or b.get("ais_name") for b in r.get("boats", []) if b.get("mmsi")}
    lookalikes = {str(c["mmsi"]): c.get("landing") for c in r.get("candidates", [])
                  if c.get("mmsi") and str(c["mmsi"]) not in fleet}
    fleet_list = {}
    for u in r.get("unmatched_fleet_list", []):
        k = norm(u.get("name"))
        if k and k not in fleet_list:
            fleet_list[k] = u.get("landing")
    dump = lambda d: json.dumps(dict(sorted(d.items())), ensure_ascii=False, indent=0).replace("\n", "")
    js = ("// Generated by fleet-model/vessel_lists.py from fleet-model/data/roster.json.\n"
          "// Do not edit by hand: rebuild the roster (or run the script) instead.\n"
          f"// MMSI -> name: the fleet roster ({len(fleet)} boats).\n"
          f"export const FLEET = {dump(fleet)};\n"
          f"// MMSI -> landing: hulls whose name is on a landing's fleet list but the roster rejected ({len(lookalikes)}).\n"
          f"export const LOOKALIKES = {dump(lookalikes)};\n"
          f"// normalised name -> landing: fleet-list boats never matched on AIS ({len(fleet_list)}).\n"
          f"export const FLEET_LIST = {dump(fleet_list)};\n")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(f"vessel lists: {len(fleet)} fleet, {len(lookalikes)} lookalikes, {len(fleet_list)} fleet-list names -> {out_path}")


if __name__ == "__main__":
    build()
